let failures = 0;
for (const [file, fields] of Object.entries(expected)) {
  const row = parseContractMessage(await Bun.file(`fixtures/${file}`).text());
  for (const [key, want] of Object.entries(fields)) {
    const got = row[key] ?? "";
    if (got !== want) {
      failures++;
      console.log(`FAIL ${file} | ${key}: got ${JSON.stringify(got)}, want ${JSON.stringify(want)}`);
    }
  }
  const errors = validateRow(row).filter((e) => !/Номер|ИНН клиента|ОГРН клиента|НПД/.test(e));
  if (errors.length) {
    failures++;
    console.log(`FAIL ${file} | validation:`, errors);
  }
}
console.log(failures === 0 ? "ALL FIXTURES OK" : `${failures} failures`);
process.exit(failures === 0 ? 0 : 1);
